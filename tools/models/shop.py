#!/usr/bin/env python3
"""
The market stall (3 × 2 cells, 1/16 scale, front = +z) and its keeper — Тоша, a red panda in an
apron (rig: body + head). Crafting items too: recipe card, paint, bait.
Writes content/shop/models.json5, content/shop/rigs.json5, content/crafting/models.json5.
Run: python3 tools/models/shop.py
"""
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


class G:
    def __init__(self):
        self.v = {}

    def box(self, x0, x1, y0, y1, z0, z1, c):
        for x in range(x0, x1 + 1):
            for y in range(y0, y1 + 1):
                for z in range(z0, z1 + 1):
                    self.v[(x, y, z)] = c(x, y, z) if callable(c) else c
        return self

    def set(self, x, y, z, c):
        self.v[(x, y, z)] = c
        return self

    def bounds(self):
        xs = [k[0] for k in self.v]; ys = [k[1] for k in self.v]; zs = [k[2] for k in self.v]
        return (min(xs), min(ys), min(zs)), (max(xs) - min(xs) + 1, max(ys) - min(ys) + 1, max(zs) - min(zs) + 1)

    def layers(self, full=None):
        (x0, y0, z0), (sx, sy, sz) = full or self.bounds()
        return [[''.join(self.v.get((x, y, z), '.') for x in range(x0, x0 + sx)) for z in range(z0, z0 + sz)] for y in range(y0, y0 + sy)]


def write(path, models, header):
    with open(path, 'w') as f:
        f.write(f'// Generated by tools/models/shop.py — {header}\n[\n')
        for m in models:
            f.write(f"  {{\n    id: '{m['id']}',\n    scale: {m['scale']},\n")
            if 'pivot' in m:
                f.write(f"    pivot: {json.dumps(m['pivot'])},\n")
            f.write(f"    palette: {json.dumps(m['palette'])},\n    layers: [\n")
            for layer in m['layers']:
                f.write('      [' + ', '.join(f"'{r}'" for r in layer) + '],\n')
            f.write('    ],\n  },\n')
        f.write(']\n')


# --- stall: 48 × 32 footprint ----------------------------------------------------------------
st = G()
W, D = 48, 32
# wooden floor boards
st.box(1, W - 2, 0, 0, 1, D - 2, lambda x, y, z: 'f' if (x // 4) % 2 else 'F')
# counter along the front (z 18..23), with crates of goods on it
st.box(2, W - 3, 1, 10, 18, 23, lambda x, y, z: 'c' if y < 10 else 'C')
for (x0, col) in [(6, 'r'), (16, 'o'), (28, 'y'), (38, 'g')]:
    st.box(x0, x0 + 5, 11, 13, 19, 22, 'k')
    st.box(x0 + 1, x0 + 4, 14, 14, 20, 21, col)
    st.set(x0 + 2, 15, 20, col).set(x0 + 3, 15, 21, col)
# back posts carry a short striped awning (the keeper stands in front of it, in view of the
# camera); front posts carry a string of little flags over the counter
for x in (1, W - 3):
    st.box(x, x + 1, 1, 34, 1, 2, 'p')
    st.box(x, x + 1, 1, 22, D - 3, D - 2, 'p')
for z in range(0, 9):
    y = 34 - z // 3
    for x in range(0, W):
        st.set(x, y, z, 'a' if (x // 6) % 2 else 'A')
for x in range(0, W):  # scalloped edge
    if x % 6 in (1, 2, 3, 4):
        st.set(x, 34 - 8 // 3 - 1, 8, 'a' if (x // 6) % 2 else 'A')
# string and flags between the front posts
for x in range(3, W - 3):
    sag = int(2 * math.sin(math.pi * (x - 3) / (W - 6)))
    st.set(x, 22 - sag, D - 3, 'k')
    if x % 5 == 0:
        col = 'rogb'[(x // 5) % 4]
        for k in range(3):
            for w in range(-1 + k // 2, 2 - (k + 1) // 2):
                st.set(x + w, 21 - sag - k, D - 3, col)
# sign board on top of the awning
st.box(14, 33, 36, 40, 1, 2, 'b')
for x in range(16, 32, 3):
    st.set(x, 38, 3, 'k').set(x + 1, 38, 3, 'k')
stall = {'id': 'shop:stall', 'scale': 0.0625, 'palette': {
    'f': '#d9a56c', 'F': '#c99560', 'c': '#b07a50', 'C': '#d9a56c', 'k': '#9a6a48', 'p': '#8a5a3a',
    'a': '#ff8fa8', 'A': '#fffaf0', 'b': '#7fcfb0', 'r': '#e8423a', 'o': '#ff9a3a', 'y': '#ffd23a', 'g': '#8fbf6a'},
    'layers': st.layers(((0, 0, 0), (W, 41, D)))}

# --- the keeper: a red panda in a green apron -------------------------------------------------
body = G()
BW, BH, BD = 10, 9, 8
for x in range(BW):
    for y in range(BH):
        for z in range(BD):
            if x in (0, BW - 1) and z in (0, BD - 1):
                continue
            c = 'o'
            if y <= 2:
                c = 'd'  # dark legs
            if z == BD - 1 and 2 <= x <= BW - 3 and 2 <= y <= BH - 2:
                c = 'a'  # apron
            body.set(x, y, z, c)
for y in range(3, 7):
    body.set(-1, y, 4, 'd').set(BW, y, 4, 'd')  # arms
body.set(4, 6, BD, 'w').set(5, 6, BD, 'w')  # apron pocket stitch
# striped tail behind
for i in range(7):
    body.box(4, 5, 1 + i // 2, 2 + i // 2, -1 - i, -1 - i, 'o' if (i // 2) % 2 == 0 else 'w')
head = G()
HW, HH, HD = 10, 8, 9
for x in range(HW):
    for y in range(HH):
        for z in range(HD):
            if x in (0, HW - 1) and y in (0, HH - 1):
                continue
            head.set(x, y, z, "o")
# white face marks: cheeks, muzzle and brows on the front face
for (x, y) in [(1, 1), (2, 1), (1, 2), (2, 2), (7, 1), (8, 1), (7, 2), (8, 2), (3, 1), (4, 1), (5, 1), (6, 1), (4, 2), (5, 2), (2, 6), (7, 6)]:
    head.set(x, y, HD - 1, 'w')
head.box(3, 6, 0, 2, HD, HD, 'w')
head.set(4, 2, HD + 1, 'n').set(5, 2, HD + 1, 'n')
head.set(2, 4, HD, 'e').set(7, 4, HD, 'e')
# ears: orange outside, white inside
for ex in (0, 8):
    head.box(ex, ex + 1, HH, HH + 1, 3, 4, 'o')
    head.set(ex + (1 if ex == 0 else 0), HH, 5, 'w')

def norm(g):
    (x0, y0, z0), size = g.bounds()
    n = G()
    n.v = {(x - x0, y - y0, z - z0): c for (x, y, z), c in g.v.items()}
    return n, (x0, y0, z0)

KEEP = {'o': '#d9643a', 'd': '#5a2e22', 'a': '#7cc45e', 'w': '#fff4e6', 'n': '#2a1e1e', 'e': '#2a2230'}
bn, bmin = norm(body)
hn, hmin = norm(head)
keeper_models = [
    {'id': 'shop:keeper_body', 'scale': 0.0625, 'palette': KEEP, 'layers': bn.layers()},
    {'id': 'shop:keeper_head', 'scale': 0.0625, 'palette': KEEP, 'layers': hn.layers()},
]
rig = {'id': 'shop:keeper', 'scale': 0.0625, 'parts': [
    {'name': 'body', 'model': 'shop:keeper_body', 'pivot': [BW / 2 - bmin[0], 0, BD / 2 - bmin[2]], 'at': [0, 0, 0]},
    {'name': 'head', 'model': 'shop:keeper_head', 'pivot': [HW / 2 - hmin[0], 0, HD / 2 - hmin[2]], 'at': [0, BH - 1, 0.5], 'parent': 'body'},
]}

write(os.path.join(ROOT, 'content', 'shop', 'models.json5'), [stall] + keeper_models, 'stall and keeper')
with open(os.path.join(ROOT, 'content', 'shop', 'rigs.json5'), 'w') as f:
    f.write('// Generated by tools/models/shop.py — the shopkeeper.\n[\n')
    f.write(f"  {{ id: '{rig['id']}', scale: {rig['scale']}, parts: [\n")
    for p in rig['parts']:
        extra = f", parent: '{p['parent']}'" if 'parent' in p else ''
        f.write(f"    {{ name: '{p['name']}', model: '{p['model']}', pivot: {json.dumps(p['pivot'])}, at: {json.dumps(p['at'])}{extra} }},\n")
    f.write('  ] },\n]\n')

# --- crafting items -----------------------------------------------------------------------------
card = G()
card.box(0, 11, 0, 0, 0, 7, lambda x, y, z: 'b' if x in (0, 11) or z in (0, 7) else 'w')
for x in range(2, 10):
    card.set(x, 1, 2, 'k' if x % 3 else 'w')
card.box(6, 9, 1, 1, 4, 5, 'p')
paint = G()
for y in range(0, 7):
    for x in range(7):
        for z in range(7):
            if math.hypot(x + 0.5 - 3.5, z + 0.5 - 3.5) <= 3.2:
                paint.set(x, y, z, 'p' if y >= 5 else ('l' if y in (2, 3) else 'm'))
paint.set(3, 7, 3, 'm').set(2, 8, 3, 'h').set(4, 8, 3, 'h').set(3, 9, 3, 'h')
bait = G()
for y in range(0, 5):
    for x in range(6):
        for z in range(6):
            if math.hypot(x + 0.5 - 3, z + 0.5 - 3) <= 2.8:
                bait.set(x, y, z, 'g' if y < 4 else 'c')
for (x, z) in [(2, 2), (3, 3), (2, 3)]:
    bait.set(x, 4, z, 'w')
crafting = [
    {'id': 'crafting:card', 'scale': 0.0625, 'palette': {'w': '#fffaf0', 'b': '#7fcfb0', 'k': '#a08c7c', 'p': '#ffb3c7'}, 'layers': card.layers()},
    {'id': 'crafting:paint', 'scale': 0.0625, 'palette': {'m': '#c9ccd4', 'l': '#ff8fa8', 'p': '#ff8fa8', 'h': '#8a8a96'}, 'layers': paint.layers()},
    {'id': 'crafting:bait', 'scale': 0.0625, 'palette': {'g': '#cdeef7', 'c': '#c99560', 'w': '#e8a090'}, 'layers': bait.layers()},
]
write(os.path.join(ROOT, 'content', 'crafting', 'models.json5'), crafting, 'crafting items')
print('stall, keeper, crafting items written')
