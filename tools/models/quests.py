#!/usr/bin/env python3
"""
Island board (a notice board, 1/16), the plaza fountain (3 × 3 cells at 1/8) and guest heads for
calendar events (badger, penguin — same conventions as villager heads, 1/12).
Writes content/quests/models.json5 and content/events/models.json5. Run: python3 tools/models/quests.py
"""
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def layers(v, x0=0, z0=0, sx=None, sz=None):
    xs = [k[0] for k in v]; ys = [k[1] for k in v]; zs = [k[2] for k in v]
    sx = sx or max(xs) + 1 - x0
    sz = sz or max(zs) + 1 - z0
    return [[''.join(v.get((x, y, z), '.') for x in range(x0, x0 + sx)) for z in range(z0, z0 + sz)] for y in range(0, max(ys) + 1)]


def write(path, models, header):
    with open(path, 'w') as f:
        f.write(f'// Generated by tools/models/quests.py — {header}\n[\n')
        for m in models:
            f.write(f"  {{\n    id: '{m['id']}',\n    scale: {m['scale']},\n    palette: {json.dumps(m['palette'])},\n    layers: [\n")
            for layer in m['layers']:
                f.write('      [' + ', '.join(f"'{r}'" for r in layer) + '],\n')
            f.write('    ],\n  },\n')
        f.write(']\n')


# notice board: two posts, a board with pinned papers, a little roof
b = {}
for x in (1, 14):
    for y in range(0, 22):
        b[(x, y, 7)] = 'q'
for x in range(0, 16):
    for y in range(8, 20):
        b[(x, y, 7)] = 'p' if x in (0, 15) or y in (8, 19) else 'c'
papers = [(2, 10, 5, 4, 'w'), (8, 13, 5, 5, 'y'), (3, 15, 4, 3, 'k'), (9, 9, 4, 3, 'w')]
for (x0, y0, w, h, c) in papers:
    for x in range(x0, x0 + w):
        for y in range(y0, y0 + h):
            b[(x, y, 8)] = c
    b[(x0 + w // 2, y0 + h - 1, 9)] = 'r'
for k, y in enumerate(range(21, 25)):
    for x in range(-1 + k, 17 - k):
        for z in range(5, 10):
            b[(x + 0, y, z)] = 'R' if z in (5, 9) else 'a'
board = {'id': 'quests:board', 'scale': 0.0625, 'palette': {'q': '#8a5a3a', 'p': '#b07a50', 'c': '#d9b48a', 'w': '#fffaf0', 'y': '#fff2b8', 'k': '#cdeee0', 'r': '#e8645a', 'a': '#6fb7a8', 'R': '#4f9a8a'}}
# shift x by +1 so the min corner is 0
board['layers'] = layers({(x + 1, y, z): c for (x, y, z), c in b.items()})

# fountain: round basin, water, a column with a bowl, sparkling top
f = {}
S = 24
c0 = 11.5
for x in range(S):
    for z in range(S):
        d = math.hypot(x - c0, z - c0)
        if d <= 11.5:
            f[(x, 0, z)] = 's'
            if d > 10:
                for y in (1, 2, 3):
                    f[(x, y, z)] = 'S' if y == 3 else 's'
            else:
                f[(x, 1, z)] = 'w'
                f[(x, 2, z)] = 'w' if (x + z) % 5 else 'W'
        if d <= 1.6:
            for y in range(3, 12):
                f[(x, y, z)] = 's'
        if d <= 4.5:
            f[(x, 12, z)] = 'S' if d > 3.5 else 'w'
        if d <= 1.2:
            f[(x, 13, z)] = 'W'
            f[(x, 14, z)] = 'W'
fountain = {'id': 'quests:fountain', 'scale': 0.125, 'palette': {'s': '#d8d2c8', 'S': '#efe8dc', 'w': '#8fd6ef', 'W': '#c9f3fb'}, 'layers': layers(f, 0, 0, S, S)}

write(os.path.join(ROOT, 'content', 'quests', 'models.json5'), [board, fountain], 'island board and fountain')


# --- guest heads ------------------------------------------------------------------------------
def head_base():
    g = {}
    for x in range(8):
        for y in range(6):
            for z in range(7):
                if x in (0, 7) and y in (0, 5):
                    continue
                g[(x, y, z)] = 's'
    g[(2, 3, 6)] = 'e'
    g[(5, 3, 6)] = 'e'
    g[(1, 2, 6)] = 'b'
    g[(6, 2, 6)] = 'b'
    return g


def badger():
    g = head_base()
    # white stripe over the head down to the nose, dark eye bands
    for y in range(0, 6):
        for z in range(0, 7):
            for x in (3, 4):
                if (x, y, z) in g and (y >= 4 or z == 6):
                    g[(x, y, z)] = 'S'
    for (x, y) in [(1, 3), (2, 4), (5, 4), (6, 3)]:
        g[(x, y, 6)] = 'd'
    g[(2, 3, 6)] = 'e'
    g[(5, 3, 6)] = 'e'
    for x in range(2, 6):
        for y in (0, 1, 2):
            g[(x, y, 7)] = 'S'
    g[(3, 2, 8)] = 'n'
    g[(4, 2, 8)] = 'n'
    for x in (0, 6):
        g[(x, 5, 3)] = 's'
        g[(x + 1, 5, 3)] = 's'
        g[(x, 6, 3)] = 'S'
    return g


def penguin():
    g = head_base()
    for (x, y, z), c in list(g.items()):
        if z == 6 and 1 <= x <= 6 and y <= 4:
            g[(x, y, z)] = 'S'
    g[(2, 3, 6)] = 'e'
    g[(5, 3, 6)] = 'e'
    for x in (3, 4):
        g[(x, 2, 7)] = 'y'
        g[(x, 2, 8)] = 'y'
        g[(x, 1, 7)] = 'y'
    # a woolly hat with a pompom
    for x in range(8):
        for z in range(7):
            g[(x, 6, z)] = 'h'
            if 1 <= x <= 6 and 1 <= z <= 5:
                g[(x, 7, z)] = 'h' if (x + z) % 2 else 'H'
    g[(3, 8, 3)] = 'H'
    g[(4, 8, 3)] = 'H'
    g[(3, 9, 3)] = 'H'
    return g


PAL = {'s': '#5a5a64', 'S': '#fffaf0', 'e': '#2a2230', 'n': '#2a1e1e', 'b': '#ffadbb', 'd': '#2a2a30', 'y': '#ffb34a', 'h': '#e8645a', 'H': '#fffaf0'}
write(os.path.join(ROOT, 'content', 'events', 'models.json5'), [
    {'id': 'events:head_badger', 'scale': 1 / 12, 'palette': PAL, 'layers': layers(badger(), 0, 0)},
    {'id': 'events:head_penguin', 'scale': 1 / 12, 'palette': PAL, 'layers': layers(penguin(), 0, 0)},
], 'guest heads')
print('board, fountain, guest heads written')
