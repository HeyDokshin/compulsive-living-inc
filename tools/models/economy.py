#!/usr/bin/env python3
"""
Economy props: the sell box (a wooden crate with a slot and a bell emblem) and a bell coin.
Writes content/economy/models.json5. Run: python3 tools/models/economy.py
"""
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'content', 'economy', 'models.json5')


def layers(cells, sx, sy, sz):
    return [[''.join(cells.get((x, y, z), '.') for x in range(sx)) for z in range(sz)] for y in range(sy)]


# sell box: 14 × 13 × 12, front (+z) has a bell emblem, the lid has a slot
box = {}
SX, SY, SZ = 14, 13, 12
for x in range(SX):
    for y in range(SY - 1):
        for z in range(SZ):
            edge = x in (0, SX - 1) or z in (0, SZ - 1) or y in (0, SY - 2)
            if not edge:
                continue
            c = 'w' if (y // 3) % 2 == 0 else 'v'  # planks
            if (x in (0, SX - 1) and z in (0, SZ - 1)) or y in (0, SY - 2):
                c = 'd'  # corner posts and rims
            box[(x, y, z)] = c
# lid with a slot
for x in range(1, SX - 1):
    for z in range(1, SZ - 1):
        box[(x, SY - 1, z)] = 'k' if 3 <= x <= SX - 4 and z in (5, 6) else 'l'
# bell emblem on the front
for (x, y) in [(6, 8), (7, 8), (5, 7), (6, 7), (7, 7), (8, 7), (5, 6), (6, 6), (7, 6), (8, 6), (4, 5), (5, 5), (6, 5), (7, 5), (8, 5), (9, 5), (4, 4), (5, 4), (6, 4), (7, 4), (8, 4), (9, 4), (6, 3), (7, 3)]:
    box[(x, y, SZ)] = 'g'
box[(6, 4, SZ + 1)] = 'h'

coin = {}
for x in range(8):
    for z in range(8):
        if math.hypot(x + 0.5 - 4, z + 0.5 - 4) <= 3.9:
            for y in range(2):
                coin[(x, y, z)] = 'g' if (x + z) % 5 else 'h'

models = [
    {'id': 'economy:sell_box', 'scale': 0.0625, 'palette': {'w': '#d9a56c', 'v': '#c99560', 'd': '#9a6a48', 'l': '#e2b27f', 'k': '#5a3e2c', 'g': '#f2c14e', 'h': '#fff2b8'}, 'layers': layers(box, SX, SY, SZ + 2)},
    {'id': 'economy:bells', 'scale': 0.0625, 'palette': {'g': '#f2c14e', 'h': '#fff2b8'}, 'layers': layers(coin, 8, 2, 8)},
]
with open(OUT, 'w') as f:
    f.write('// Generated by tools/models/economy.py\n[\n')
    for m in models:
        f.write(f"  {{\n    id: '{m['id']}',\n    scale: {m['scale']},\n    palette: {json.dumps(m['palette'])},\n    layers: [\n")
        for layer in m['layers']:
            f.write('      [' + ', '.join(f"'{r}'" for r in layer) + '],\n')
        f.write('    ],\n  },\n')
    f.write(']\n')
print(f'{len(models)} models → {os.path.relpath(OUT, ROOT)}')
